import type { Locale } from '../i18n';
import benchmarkArtifact from '../levels/temporal-benchmark.json';

interface Translator {
  (key: string, params?: Readonly<Record<string, string | number>>): string;
}

type BenchmarkModel = (typeof benchmarkArtifact.models)[number];

const focusByLevel: Readonly<Record<string, BenchmarkModel>> = {
  'time-window-limit': 'fixed-window',
  'time-rnn': 'rnn',
  'time-rnn-window': 'rnn',
  'time-rnn-delay': 'rnn',
  'time-attention': 'rnn-attention',
  'time-forecast': 'rnn-attention',
};

/** Levels that come before attention is taught must not show attention evidence. */
const attentionLevels: ReadonlySet<string> = new Set(['time-attention', 'time-forecast']);

/** MSE spans several orders of magnitude, so use one scientific style: 7.83e-2, 1.39e-4. */
export function formatMse(value: number): string {
  if (value === 0) return '0';
  const [mantissa, exponent] = value.toExponential(2).split('e');
  return `${mantissa}e${Number(exponent)}`;
}

function formatWeight(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale, {
    maximumFractionDigits: 2,
    minimumFractionDigits: 2,
  }).format(value);
}

/** Fixed, reproducible CPU evidence generated by the project's own training engine. */
export function TemporalBenchmarkEvidence({
  levelId,
  locale,
  t,
}: {
  levelId: string;
  locale: Locale;
  t: Translator;
}) {
  const focus = focusByLevel[levelId];
  if (!focus) return null;
  const showAttentionProbe = levelId === 'time-attention';

  const results = benchmarkArtifact.results.filter(
    (result) => attentionLevels.has(levelId) || result.model !== 'rnn-attention',
  );
  const focusResult = results.find((result) => result.model === focus);
  const best = Math.min(...results.flatMap((result) => result.delays.map((d) => d.meanMse)));

  return (
    <section className="benchmark-evidence" aria-label={t('benchmark.title')}>
      <h2 className="label">{t('benchmark.title')}</h2>
      {focusResult && (
        <p className="benchmark-lede">
          {t('benchmark.lede', { model: t(`benchmark.model.${focus}`) })}
        </p>
      )}
      <table className="table benchmark-table">
        <thead>
          <tr>
            <th>{t('benchmark.model')}</th>
            {benchmarkArtifact.delays.map((delay) => (
              <th key={delay}>{t('benchmark.delay', { delay })}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {results.map((result) => (
            <tr className={result.model === focus ? 'is-focus' : ''} key={result.model}>
              <th scope="row">
                {t(`benchmark.model.${result.model}`)}
                <small>
                  {t('benchmark.parameterCount', {
                    n: new Intl.NumberFormat(locale).format(result.parameterCount),
                  })}
                </small>
              </th>
              {result.delays.map((measurement) => (
                <td
                  key={measurement.delay}
                  className={measurement.meanMse === best ? 'is-best' : undefined}
                  data-label={t('benchmark.delay', { delay: measurement.delay })}
                >
                  {formatMse(measurement.meanMse)}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
      <p className="benchmark-note">{t('benchmark.reading')}</p>
      {showAttentionProbe && (
        <div className="attention-probe">
          <h3 className="label">{t('benchmark.attentionProbe')}</h3>
          <div className="attention-weights">
            {benchmarkArtifact.attentionProbe.weights.map((weight, index) => (
              <div
                className={index === 1 ? 'attention-weight is-match' : 'attention-weight'}
                key={index}
              >
                <span>{t('benchmark.position', { position: index + 1 })}</span>
                <span className="attention-weight-track" aria-hidden="true">
                  <span style={{ width: `${weight * 100}%` }} />
                </span>
                <strong>{formatWeight(locale, weight)}</strong>
              </div>
            ))}
          </div>
          <p className="benchmark-note">
            {t('benchmark.attentionProbeNote', {
              position: 2,
              weight: formatWeight(locale, benchmarkArtifact.attentionProbe.weights[1]),
            })}
          </p>
        </div>
      )}
      <details className="experiment-details">
        <summary>{t('benchmark.methodTitle')}</summary>
        <p>
          {t('benchmark.method', {
            steps: benchmarkArtifact.training.steps,
            batch: benchmarkArtifact.training.batchSize,
            evaluation: benchmarkArtifact.training.evaluationBatchSize,
          })}{' '}
          {t('benchmark.seed', { seed: benchmarkArtifact.seeds[0] })}
        </p>
      </details>
    </section>
  );
}
